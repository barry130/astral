/** Public save/read contract with real MyBatis SQL against an isolated in-memory database. */
class AiMcpServerPersistenceTest {
    private SqlSession session;
    private AiMcpServerService service;

    @BeforeEach
    void setUp() {
        JdbcDataSource dataSource = new JdbcDataSource();
        dataSource.setURL("jdbc:h2:mem:mcp_" + UUID.randomUUID() + ";MODE=PostgreSQL");
        MybatisConfiguration config = new MybatisConfiguration();
        config.setEnvironment(new Environment("test", new JdbcTransactionFactory(), dataSource));
        AtomicLong ids = new AtomicLong(1000);
        GlobalConfigUtils.setGlobalConfig(
                config,
                new GlobalConfig()
                        .setDbConfig(new GlobalConfig.DbConfig())
                        .setMetaObjectHandler(new MetaObjectHandler() {
                            @Override
                            public void insertFill(MetaObject object) {
                                setFieldValByName("id", ids.incrementAndGet(), object);
                            }

                            @Override
                            public void updateFill(MetaObject object) {
                                // Timestamp filling is unrelated to the credential persistence contract.
                            }
                        }));
        config.addMapper(AiMcpServerMapper.class);
        session = new MybatisSqlSessionFactoryBuilder().build(config).openSession(true);
        // Keep the database alive for the public service calls below.
        session.getConnection();
        JdbcTemplate jdbc = new JdbcTemplate(dataSource);
        jdbc.execute("""
                CREATE TABLE ai_mcp_server (
                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                  server_code VARCHAR(64), name VARCHAR(128), url VARCHAR(512), headers_json TEXT,
                  read_only BOOLEAN, status VARCHAR(16), tool_count INTEGER,
                  last_refresh_time TIMESTAMP, last_error TEXT, created_by BIGINT, updated_by BIGINT,
                  create_time TIMESTAMP, update_time TIMESTAMP)
                """);
        AiProperties properties = new AiProperties();
        properties.setSecretKey("unit-test-kek");
        AiMcpServerMapper servers = session.getMapper(AiMcpServerMapper.class);
        AiToolMapper tools = mock(AiToolMapper.class);
        when(tools.selectList(any())).thenReturn(List.of());
        service = new AiMcpServerService(servers, new AiMcpServerFailureRecorder(servers), tools, properties);
    }

    @AfterEach
    void tearDown() {
        if (session != null) {
            session.close();
        }
    }

    @Test
    void clearingHeadersRemovesStoredCredentialsOnTheNextRead() {
        var created = service.create(body("{\"Authorization\":\"Bearer private-fixture\"}"), 41L);
        Long id = service.list().getFirst().getId();
        assertTrue(created.getHeadersJson().contains("v1:"));

        service.update(id, body(""), 41L);

        assertNull(service.require(id).getHeadersJson(), "cleared credentials must not survive in the database");
    }

    @Test
    void creatingServerAuditsOutcomeWithoutCopyingHeaderCredentials() {
        OperateLogMapper logs = mock(OperateLogMapper.class);
        OperateLogWriter writer = new OperateLogWriter(new LogServiceImpl(logs, mock(LoginLogMapper.class)));
        AspectJProxyFactory factory = new AspectJProxyFactory(new AiAdminMcpController(service));
        factory.addAspect(new OperateLogAspect(writer, new ObjectMapper()));
        AiAdminMcpController controller = factory.getProxy();
        MockHttpServletRequest request = new MockHttpServletRequest("POST", "/api/v1/admin/ai/mcp-servers");
        request.setAttribute("userId", "41");

        var result = controller.createServer(body("{\"Authorization\":\"Bearer confidential-fixture\"}"), request);

        assertEquals(200, result.getCode());
        ArgumentCaptor<OperateLog> saved = ArgumentCaptor.forClass(OperateLog.class);
        verify(logs).insert(saved.capture());
        assertEquals(1, saved.getValue().getStatus());
        assertFalse(AiJson.write(saved.getValue()).contains("confidential-fixture"));
    }

    private static AiAdminDtos.McpServerSaveReq body(String headers) {
        return new AiAdminDtos.McpServerSaveReq(
                "fixture_server", "Fixture", "https://93.184.216.34/mcp", headers, true, null);
    }
}
