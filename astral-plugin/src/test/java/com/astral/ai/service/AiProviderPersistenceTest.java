package com.astral.ai.service;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.mockito.Mockito.mock;

import com.astral.ai.common.AiJson;
import com.astral.ai.config.AiProperties;
import com.astral.ai.entity.AiProviderEntity;
import com.astral.ai.mapper.AiModelMapper;
import com.astral.ai.mapper.AiProviderMapper;
import com.astral.ai.mapper.AiProviderRouteMapper;
import com.astral.ai.provider.AiProviderRegistry;
import com.astral.ai.provider.MockAiProvider;
import com.astral.ai.security.AiSecretCipher;
import com.astral.ai.tool.AdminToolProvider;
import com.astral.ai.tool.AiToolTypes.AiToolContext;
import com.astral.ai.tool.AiToolTypes.AiToolResult;
import com.baomidou.mybatisplus.core.MybatisConfiguration;
import com.baomidou.mybatisplus.core.MybatisSqlSessionFactoryBuilder;
import com.baomidou.mybatisplus.core.config.GlobalConfig;
import com.baomidou.mybatisplus.core.handlers.MetaObjectHandler;
import com.baomidou.mybatisplus.core.toolkit.GlobalConfigUtils;
import java.util.List;
import java.util.UUID;
import org.apache.ibatis.executor.Executor;
import org.apache.ibatis.mapping.Environment;
import org.apache.ibatis.mapping.MappedStatement;
import org.apache.ibatis.plugin.Interceptor;
import org.apache.ibatis.plugin.Intercepts;
import org.apache.ibatis.plugin.Invocation;
import org.apache.ibatis.plugin.Signature;
import org.apache.ibatis.reflection.MetaObject;
import org.apache.ibatis.session.SqlSession;
import org.apache.ibatis.transaction.jdbc.JdbcTransactionFactory;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;

class AiProviderPersistenceTest {
    private SqlSession session;
    private AiProviderService service;
    private AiSecretCipher cipher;
    private JdbcTemplate jdbc;
    private Runnable beforeWrite;

    @BeforeEach
    void setUp() {
        JdbcDataSource source = new JdbcDataSource();
        source.setURL("jdbc:h2:mem:provider_" + UUID.randomUUID() + ";MODE=PostgreSQL");
        MybatisConfiguration config = new MybatisConfiguration();
        config.setEnvironment(new Environment("test", new JdbcTransactionFactory(), source));
        GlobalConfigUtils.setGlobalConfig(
                config,
                new GlobalConfig()
                        .setDbConfig(new GlobalConfig.DbConfig())
                        .setMetaObjectHandler(new MetaObjectHandler() {
                            @Override
                            public void insertFill(MetaObject object) {
                                setFieldValByName("id", 1001L, object);
                            }

                            @Override
                            public void updateFill(MetaObject object) {
                                // The test verifies explicit column persistence, not timestamps.
                            }
                        }));
        config.addInterceptor(new WriteInterleaving());
        config.addMapper(AiProviderMapper.class);
        session = new MybatisSqlSessionFactoryBuilder().build(config).openSession(true);
        session.getConnection();
        jdbc = new JdbcTemplate(source);
        jdbc.execute("""
                CREATE TABLE ai_provider(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                provider_code VARCHAR(64),name VARCHAR(128),provider_type VARCHAR(32),base_url VARCHAR(512),
                enabled BOOLEAN,secret_ref VARCHAR(128),encrypted_api_key TEXT,connect_timeout_ms INTEGER,
                read_timeout_ms INTEGER,max_retries INTEGER,weight INTEGER,health_status VARCHAR(16),
                last_health_time TIMESTAMP,last_health_message VARCHAR(400),remark VARCHAR(512),
                created_by BIGINT,updated_by BIGINT,create_time TIMESTAMP,update_time TIMESTAMP)
                """);
        AiProperties properties = new AiProperties();
        properties.setSecretKey("synthetic-provider-kek");
        cipher = new AiSecretCipher(properties);
        service = new AiProviderService(
                session.getMapper(AiProviderMapper.class),
                mock(AiModelMapper.class),
                mock(AiProviderRouteMapper.class),
                new AiProviderRegistry(List.of(new MockAiProvider())),
                cipher);
        jdbc.update(
                "INSERT INTO ai_provider(id,provider_code,name,provider_type,base_url,enabled,encrypted_api_key) VALUES (10,'fixture','Fixture','MOCK','mock://local',true,?)",
                cipher.encrypt("original-fixture-key"));
    }

    @AfterEach
    void tearDown() {
        session.close();
    }

    @Test
    void switchingToReferenceRemovesStoredKeyOnNextRead() {
        update(null, "env:FIXTURE_AI_KEY");
        AiProviderEntity saved = service.require(10L);
        assertNull(saved.getEncryptedApiKey());
        assertEquals("env:FIXTURE_AI_KEY", saved.getSecretRef());
        assertEquals("SECRET_REF", service.credentialSource(saved));
    }

    @Test
    void switchingToNewKeyRemovesReferenceOnNextRead() {
        jdbc.update("UPDATE ai_provider SET encrypted_api_key=NULL,secret_ref='env:FIXTURE_AI_KEY' WHERE id=10");
        update("new-fixture-key", null);
        AiProviderEntity saved = service.require(10L);
        assertNull(saved.getSecretRef());
        assertEquals("new-fixture-key", service.resolveApiKey(saved));
    }

    @Test
    void clearingReferenceIsPersistedWhileBlankKeyDoesNotClearStoredKey() {
        update("", "");
        assertEquals("original-fixture-key", service.resolveApiKey(service.require(10L)));
        jdbc.update("UPDATE ai_provider SET encrypted_api_key=NULL,secret_ref='env:FIXTURE_AI_KEY' WHERE id=10");
        session.clearCache();
        update("", "");
        assertNull(service.require(10L).getSecretRef());
        assertEquals("NONE", service.credentialSource(service.require(10L)));
    }

    @Test
    void omittedCredentialsKeepExistingKey() {
        update(null, null);
        assertEquals("original-fixture-key", service.resolveApiKey(service.require(10L)));
    }

    @Test
    void createUsesSingleCredentialSourceWithExplicitKeyTakingPriority() {
        service.create(
                "new_fixture",
                "New",
                "MOCK",
                null,
                "new-key",
                "env:IGNORED_REF",
                true,
                null,
                null,
                null,
                null,
                null,
                41L);
        var saved = service.list().stream()
                .filter(row -> row.getProviderCode().equals("new_fixture"))
                .findFirst()
                .orElseThrow();
        assertNull(saved.getSecretRef());
        assertEquals("new-key", service.resolveApiKey(saved));
    }

    @Test
    void credentialUpdatePreservesSeparatelyCommittedNameAndHealth() {
        jdbc.update("UPDATE ai_provider SET health_status='UNKNOWN' WHERE id=10");
        beforeWrite =
                () -> jdbc.update("UPDATE ai_provider SET name='Concurrent rename',health_status='UP' WHERE id=10");
        update("new-key", null);
        AiProviderEntity saved = service.require(10L);
        assertEquals("Concurrent rename", saved.getName());
        assertEquals("UP", saved.getHealthStatus());
    }

    @Test
    void assistantDisableOnlyChangesEnabledState() {
        jdbc.update("UPDATE ai_provider SET secret_ref='env:OLD_FIXTURE_REF',encrypted_api_key=NULL WHERE id=10");
        beforeWrite = () -> jdbc.update(
                "UPDATE ai_provider SET name='Concurrent name',secret_ref=NULL,encrypted_api_key=? WHERE id=10",
                cipher.encrypt("rotated-fixture-key"));
        var provider = new AdminToolProvider(
                null, null, null, null, null, null, null, service, null, null, null, null, null, null, null, null);
        var result = provider.handlers().stream()
                .filter(handler ->
                        "disable_provider".equals(handler.definition().toolCode()))
                .findFirst()
                .orElseThrow()
                .execute(new AiToolContext(
                        1L,
                        2L,
                        3L,
                        4L,
                        "fixture",
                        "ADMIN",
                        "ASTRAL_FRONT",
                        AiJson.mapper().createObjectNode().put("providerId", 10),
                        null,
                        true,
                        3L));
        assertEquals(AiToolResult.SUCCEEDED, result.status());
        var saved = service.require(10L);
        assertEquals(false, saved.getEnabled());
        assertEquals("Concurrent name", saved.getName());
        assertEquals("rotated-fixture-key", service.resolveApiKey(saved));
    }

    @Intercepts(
            @Signature(
                    type = Executor.class,
                    method = "update",
                    args = {MappedStatement.class, Object.class}))
    private class WriteInterleaving implements Interceptor {
        @Override
        public Object intercept(Invocation invocation) throws Throwable {
            if (beforeWrite != null) {
                Runnable action = beforeWrite;
                beforeWrite = null;
                action.run();
            }
            return invocation.proceed();
        }
    }

    private void update(String key, String ref) {
        service.update(10L, null, null, null, key, ref, null, null, null, null, null, null, 41L);
    }
}
